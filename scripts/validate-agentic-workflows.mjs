import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  extractWorkflowBody,
  validateCompiledReadOnlyTools,
  validateFinalInstruction,
  validateSdkInstallIntegrity,
} from "./agentic-workflow-contract.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, ".github", "workflows", "agent-findings-audit.md");
const lockPath = path.join(root, ".github", "workflows", "agent-findings-audit.lock.yml");
const source = fs.readFileSync(sourcePath, "utf8");
const lock = fs.readFileSync(lockPath, "utf8");
const sdkRuntimePath = path.join(root, ".github", "aw", "copilot-sdk-runtime");
const sdkManifest = JSON.parse(fs.readFileSync(path.join(sdkRuntimePath, "package.json"), "utf8"));
const sdkLockText = fs.readFileSync(path.join(sdkRuntimePath, "package-lock.json"), "utf8");
const sdkLock = JSON.parse(sdkLockText);
const workflowBody = extractWorkflowBody(source);

assert.match(source, /^\s*edit: false\s*$/m, "findings audit must disable edit");
assert.match(source, /^\s*bash: false\s*$/m, "findings audit must disable bash");
assert.match(source, /^\s*cli-proxy: false\s*$/m, "findings audit must disable CLI proxy tools");
assert.match(source, /^\s*github: false\s*$/m, "findings audit must disable GitHub MCP tools");
assert.match(source, /^\s*copilot-sdk: true\s*$/m, "findings audit must use SDK tool isolation");
assert.match(source, /^\s*strict: true\s*$/m, "findings audit must use strict mode");
assert.match(source, /^\s*gh-aw-detection: false\s*$/m, "findings audit must use the supported inline detector");
assert.match(source, /^\s*max-turns: 40\s*$/m, "findings audit must retain its bounded completion budget");
validateFinalInstruction(workflowBody);

const manifestPrefix = "# gh-aw-manifest: ";
const manifestLine = lock.split(/\r?\n/u).find((line) => line.startsWith(manifestPrefix));
assert.ok(manifestLine, "compiled workflow must contain a gh-aw manifest");
const manifest = JSON.parse(manifestLine.slice(manifestPrefix.length));
assert.deepEqual(manifest.mcp_servers, [
  {
    name: "safeoutputs",
    tools: ["noop", "submit_findings_audit_report"],
  },
]);
assert.match(lock, /Tools: noop, submit_findings_audit_report/u, "compiled prompt must expose the final report tool");
validateCompiledReadOnlyTools(lock);
validateSdkInstallIntegrity(source, lock, sdkManifest, sdkLock, sdkLockText);
assert.match(
  lock,
  /\{\{#runtime-import \.github\/workflows\/agent-findings-audit\.md\}\}/u,
  "compiled prompt must import the validated workflow source body",
);

assert.doesNotMatch(
  lock,
  /^\s+(?:contents|issues|pull-requests|checks|deployments): write\s*$/mu,
  "compiled audit must not grant persistent repository write permissions",
);
assert.match(lock, /generated by gh-aw \(v0\.88\.7\)/u, "compiled workflow must use pinned gh-aw v0.88.7");
assert.match(lock, /GH_AW_INFO_FIREWALL_ENABLED: "true"/u, "compiled workflow must enable the firewall");
assert.match(
  lock,
  /GH_AW_INFO_FEATURES: '\{"gh-aw-detection":false\}'/u,
  "compiled workflow must select inline detection",
);
assert.match(lock, /GH_AW_PHASE: detection/u, "compiled workflow must run an isolated detection phase");
assert.match(lock, /name: Parse and conclude threat detection/u, "compiled workflow must conclude threat detection");
assert.doesNotMatch(
  lock,
  /name: Install threat-detect binary/u,
  "compiled workflow must not use the unavailable detector binary",
);
assert.match(lock, /GH_AW_MAX_AI_CREDITS: "100"/u, "compiled workflow must enforce its AI credit budget");
assert.match(lock, /Buffer\.byteLength\(report, "utf8"\) > 262144/u, "report output must remain bounded");

console.log("agentic-workflows: strict read-only contract valid");
