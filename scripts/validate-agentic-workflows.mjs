import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, ".github", "workflows", "agent-findings-audit.md");
const lockPath = path.join(root, ".github", "workflows", "agent-findings-audit.lock.yml");
const source = fs.readFileSync(sourcePath, "utf8");
const lock = fs.readFileSync(lockPath, "utf8");

assert.match(source, /^\s*edit: false\s*$/m, "findings audit must disable edit");
assert.match(source, /^\s*bash: false\s*$/m, "findings audit must disable bash");
assert.match(source, /^\s*cli-proxy: false\s*$/m, "findings audit must disable CLI proxy tools");
assert.match(source, /^\s*github: false\s*$/m, "findings audit must disable GitHub MCP tools");
assert.match(source, /^\s*strict: true\s*$/m, "findings audit must use strict mode");
assert.match(source, /^\s*max-turns: 40\s*$/m, "findings audit must retain its bounded completion budget");

const manifestPrefix = "# gh-aw-manifest: ";
const manifestLine = lock.split(/\r?\n/u).find((line) => line.startsWith(manifestPrefix));
assert.ok(manifestLine, "compiled workflow must contain a gh-aw manifest");
const manifest = JSON.parse(manifestLine.slice(manifestPrefix.length));
assert.deepEqual(manifest.mcp_servers, [
  {
    name: "safeoutputs",
    tools: ["archive_findings_audit", "noop"],
  },
]);

assert.doesNotMatch(
  lock,
  /^\s+(?:contents|issues|pull-requests|checks|deployments): write\s*$/mu,
  "compiled audit must not grant persistent repository write permissions",
);
assert.match(lock, /generated by gh-aw \(v0\.88\.7\)/u, "compiled workflow must use pinned gh-aw v0.88.7");
assert.match(lock, /GH_AW_INFO_FIREWALL_ENABLED: "true"/u, "compiled workflow must enable the firewall");
assert.match(lock, /name: Execute threat detection with AWF/u, "compiled workflow must run threat detection");
assert.match(lock, /GH_AW_MAX_AI_CREDITS: "100"/u, "compiled workflow must enforce its AI credit budget");
assert.match(lock, /Buffer\.byteLength\(report, "utf8"\) > 262144/u, "report output must remain bounded");

console.log("agentic-workflows: strict read-only contract valid");
